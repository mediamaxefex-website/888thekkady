(() => {
  const grid = document.getElementById('photo-grid');
  if (!grid) return;
  const filters = [...document.querySelectorAll('[data-filter]')];
  const count = document.querySelector('.gallery-count');
  const lightbox = document.getElementById('gallery-lightbox');
  const lbImg = lightbox.querySelector('img');
  const caption = lightbox.querySelector('figcaption');
  let visible = galleryItems.slice();
  let current = 0;
  function render(filter='all') {
    visible = galleryItems.filter(item => filter === 'all' || item.category === filter);
    grid.innerHTML = visible.map((item, i) => `<button class="photo-card" type="button" data-photo="${i}" aria-label="View ${item.alt}"><img src="${item.src}" alt="${item.alt}" loading="lazy" decoding="async"><span>${item.label}</span></button>`).join('');
    count.textContent = `${visible.length} photos`;
    filters.forEach(btn => { const active = btn.dataset.filter === filter; btn.classList.toggle('is-active', active); btn.setAttribute('aria-pressed', String(active)); });
  }
  function openPhoto(i) { current = i; const item = visible[current]; if (!item) return; lbImg.src = item.src; lbImg.alt = item.alt; caption.textContent = item.label; lightbox.hidden = false; document.body.classList.add('lightbox-open'); lightbox.querySelector('.lightbox-close').focus(); }
  function closePhoto() { lightbox.hidden = true; document.body.classList.remove('lightbox-open'); }
  function movePhoto(dir) { openPhoto((current + dir + visible.length) % visible.length); }
  filters.forEach(btn => btn.addEventListener('click', () => render(btn.dataset.filter)));
  grid.addEventListener('click', e => { const card = e.target.closest('[data-photo]'); if (card) openPhoto(Number(card.dataset.photo)); });
  lightbox.querySelector('.lightbox-close').addEventListener('click', closePhoto);
  lightbox.querySelector('.lightbox-prev').addEventListener('click', () => movePhoto(-1));
  lightbox.querySelector('.lightbox-next').addEventListener('click', () => movePhoto(1));
  lightbox.addEventListener('click', e => { if (e.target === lightbox) closePhoto(); });
  document.addEventListener('keydown', e => { if (lightbox.hidden) return; if (e.key === 'Escape') closePhoto(); if (e.key === 'ArrowLeft') movePhoto(-1); if (e.key === 'ArrowRight') movePhoto(1); });
  render();
})();
